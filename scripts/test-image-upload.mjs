import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
function compile(path, customRequire = require, globals = {}) {
  const code = ts.transpileModule(fs.readFileSync(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const exports = {};
  vm.runInNewContext(code, { exports, require: customRequire, ...globals });
  return exports;
}
const validation = compile('src/lib/platform/validation.ts');
let fetchImpl, calls = 0;
const { uploadImages } = compile('src/lib/upload-images.ts', id => id === '@/lib/platform/validation' ? validation : require(id), { FormData, fetch: (...args) => { calls++; return fetchImpl(...args); } });
const photo = name => new File(['photo-bytes'], name, { type: 'image/png' });
const ok = url => Response.json({success:true,url});
let passed = 0;
function check(value, message) { assert.ok(value, message); console.log('PASS '+message); passed++; }
const progress=[], attached=[];
let resolveFirst;
fetchImpl = () => new Promise(resolve => {resolveFirst = resolve;});
const pending=uploadImages([photo('first.png'),photo('second.png')],{onProgress:p=>progress.push({...p}),onUploaded:url=>attached.push(url)});
check(progress[0].completed===0&&progress[0].total===2&&progress[0].fileName==='first.png'&&attached.length===0,'Uploading state starts before the first request finishes');
fetchImpl=async()=>Response.json({success:false,error:'Image storage unavailable'},{status:400});
resolveFirst(ok('https://example.com/first.png'));
await assert.rejects(pending,/second.png: Image storage unavailable/);
check(attached.length===1&&attached[0]==='https://example.com/first.png','Completed photo is retained when a later upload fails');
check(progress.at(-1).completed===1&&progress.at(-1).fileName==='second.png','Failure progress identifies the unfinished photo');
fetchImpl=async()=>ok('https://example.com/second.png');
const retried=await uploadImages([photo('second.png')],{onUploaded:url=>attached.push(url)});
check(retried.length===1&&attached.length===2,'Retry adds the failed photo without losing earlier photos');
const before=calls;
await assert.rejects(uploadImages([new File([], 'empty.png', {type:'image/png'})]),/non-empty/);
await assert.rejects(uploadImages([new File(['x'], 'document.pdf', {type:'application\/pdf'})]),/JPEG/);
check(calls===before,'Invalid files are rejected before any network request');
fetchImpl=async()=>Response.json({success:true});
await assert.rejects(uploadImages([photo('missing-url.png')]),/Upload failed/);
check(true,'A success response without a valid image URL is rejected');
fetchImpl=async()=>new Response('Request too large',{status:413});
await assert.rejects(uploadImages([photo('large.png')]),/too large/);
check(true,'Server size limits give actionable feedback');
fetchImpl=async()=>{throw new TypeError('Failed to fetch');};
await assert.rejects(uploadImages([photo('offline.png')]),/Check your connection/);
check(true,'Network errors include retry guidance');
const payload={name:'Test Property',address:'Test address, Lagos',city:'Lagos',description:'A complete description of a real property.',heroImage:'https://example.com/first.png',gallery:['https://example.com/first.png']};
check(validation.propertyInput.safeParse(payload).success,'Valid uploaded images and property fields satisfy the server schema');
check(!validation.propertyInput.safeParse({...payload,city:'',description:'Fully Uploaded',gallery:['']}).success,'The originally failing form values are correctly rejected');
console.log(`${passed} image upload and property-validation checks passed.`);
